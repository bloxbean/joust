// A Counter on a local Yaci DevKit, called from Node: `npm start` (or `npm run build`, `npm run deploy`, `node index.js`).
//
// `joust build` turned contracts/app/Counter.* into a validator and a typed client, build/joust/Counter.js. Each call
// below runs the contract's own code in JOUST's runtime engine to compute the new state, builds the transaction, signs
// it with a DevKit key and submits it. On chain, the validator runs the same code again and checks the result.
import { readFileSync, existsSync } from 'node:fs';
import { generateMnemonic } from '@scure/bip39';
import { wordlist } from '@scure/bip39/wordlists/english';
import { joustRuntime, devWallet, devkitTopUp } from '@julclang/joust-runtime';
import { Counter } from './build/joust/Counter.js';   // generated by `joust build`

const read = (f) => JSON.parse(readFileSync(new URL(f, import.meta.url), 'utf8'));
if (!existsSync(new URL('build/joust/deployments.devkit.json', import.meta.url))) {
  console.error('No deployment yet: run `npm run deploy` (with a DevKit: yaci-devkit up --enable-yaci-store).');
  process.exit(1);
}
const config = read('joust.config.json');
const deployed = read('build/joust/deployments.devkit.json');   // `joust deploy`: the contract's reference script

// The runtime: the chain (DevKit's Yaci Store), the compiled contracts and where they are deployed.
const rt = joustRuntime({
  chainUrl: deployed.chain, networkId: deployed.networkId, clock: deployed.clock, ttlMs: 20_000,
  contracts: read('build/joust/contracts.json'), deployments: deployed.contracts,
});

// A throwaway wallet, funded with 100 ADA by the DevKit's faucet.
const wallet = devWallet({ chain: rt.chain, mnemonic: generateMnemonic(wordlist, 256) });
await devkitTopUp(wallet.address, 100, config.networks.devkit.admin, { chain: rt.chain });
for (let i = 0; i < 30 && !(await rt.chain.utxosAt(wallet.address)).length; i++) await new Promise((r) => setTimeout(r, 1000));
console.log('wallet     ', wallet.address);

const counter = new Counter(rt.options('app.Counter'));

// init: a new counter (its own state UTxO and thread token), owned by this wallet.
const { instance, txHash } = await counter.deploy(wallet, {});
console.log('created    ', instance.id, 'tx', txHash);

// increment: anyone may call it.
console.log('increment 5', 'tx', (await instance.increment(wallet, { by: 5n })).txHash);
console.log('increment 2', 'tx', (await instance.increment(wallet, { by: 2n })).txHash);
console.log('count      ', (await instance.state()).count);   // 7n, read from the chain

// The contract's own check refuses this before anything is signed.
await instance.increment(wallet, { by: 0n }).catch((e) => console.log('refused    ', e.message));

// close: owner only; the deposit goes back to the owner.
console.log('closed     ', 'tx', (await instance.close(wallet)).txHash);
console.log('state      ', await instance.state());          // null: the counter is gone
