// Generates a typed client (<Contract>.js + <Contract>.d.ts) from a JOUST contract description (ADR-0013 D3).
// The description is inlined into the generated module, so the page pins it: the service never supplies it.

import { isBool, isOptional } from './data.js';

const id = (s) => s.replace(/[^A-Za-z0-9_$]/g, '_');

/** TypeScript names for the description's definitions: the shortest unique suffix of each key. */
function typeNames(description) {
  const pkg = description['x-joust'].package + '.';
  const names = new Map();
  for (const key of Object.keys(description.definitions)) {
    const local = key.startsWith(pkg) ? key.slice(pkg.length) : key.slice(key.lastIndexOf('.') + 1);
    let name = id(local.split('.').join(''));
    while ([...names.values()].includes(name)) name = '_' + name;
    names.set(key, name);
  }
  return names;
}

function tsType(schema, defs, names, input) {
  if (schema.$ref) {
    const key = schema.$ref.slice('#/definitions/'.length).replace(/~1/g, '/').replace(/~0/g, '~');
    return names.get(key) + (input ? 'In' : '');
  }
  if (schema.dataType === 'integer') return input ? 'Int' : 'bigint';
  if (schema.dataType === 'bytes') return 'Hex';
  if (schema.dataType === 'list') return `Array<${tsType(schema.items, defs, names, input)}>`;
  if (schema.dataType === 'map') return `Array<[${tsType(schema.keys, defs, names, input)}, ${tsType(schema.values, defs, names, input)}]>`;
  if (schema.anyOf) {
    if (isBool(schema)) return 'boolean';
    if (isOptional(schema)) return `${tsType(schema.anyOf[0].fields[0], defs, names, input)} | null`;
    return schema.anyOf.map((c) => constructorType(c, defs, names, input, schema.anyOf.length > 1)).join(' | ');
  }
  if (schema.dataType === 'constructor') return constructorType(schema, defs, names, input, false);
  return 'DataHex';
}

function constructorType(c, defs, names, input, variant) {
  const fields = c.fields.map((f) => `${JSON.stringify(f.title)}: ${tsType(f, defs, names, input)}`);
  if (variant) fields.unshift(`$variant: ${JSON.stringify(c.title)}`);
  return `{ ${fields.join('; ')} }`;
}

/** { js, dts } for one description. */
export function generate(description, { importFrom = '@julclang/state-client' } = {}) {
  const x = description['x-joust'];
  const C = id(x.contract);
  const names = typeNames(description);
  const defs = description.definitions;
  const jsLines = [];
  const ts = [];
  const js = (s = '') => jsLines.push(s);
  const argsType = (m) => (m.args.length ? `{ ${m.args.map((a) => `${JSON.stringify(a.name)}: ${tsType(a.schema, defs, names, true)}`).join('; ')} }` : 'Record<string, never>');
  const payParam = (m) => (m.payable ? ', pay: Pay' : '');
  const doc = (m) => `  /** ${m.kind} ${x.contract}.${m.name}${m.payable ? ' (payable)' : ''}${m.policies?.signedBy?.length ? '; signed by ' + m.policies.signedBy.join(', ') : ''}. */`;
  // Every call is generated (ADR-0015 M4): calls that need the runtime (MerkleMaps, reads, sends, moves, deposits,
  // batches) are prepared by the engine, in a page's worker or a service, and the page verifier covers each of them
  // with tamper tests (I5). ADR-0013 left them out when a page could neither prepare nor verify them.
  const usable = () => true;

  js(`// GENERATED by joust-gen from ${description.preamble.title}. Do not edit.`);
  js(`// The description is pinned here: the page verifies every prepared transaction against it (ADR-0013 D2).`);
  js(`import { JoustContract } from '${importFrom}';`);
  js();
  js(`export const description = ${JSON.stringify(description)};`);
  js();

  ts.push(`// GENERATED by joust-gen from ${description.preamble.title}. Do not edit.`);
  ts.push(`import type { JoustContract, JoustOptions, CallResult, Cip30Api, Pay, Int, Hex, DataHex } from '${importFrom}';`);
  ts.push('');
  for (const [key, name] of names) {
    ts.push(`export type ${name} = ${tsType(defs[key], defs, names, false)};`);
    ts.push(`export type ${name}In = ${tsType(defs[key], defs, names, true)};`);
  }
  ts.push(`export declare const description: unknown;`);
  ts.push('');

  const stateT = tsType(x.state, defs, names, false);
  const init = x.creations.find((c) => c.kind === 'init');

  // ---- the contract
  js(`export class ${C} {`);
  js(`  /** @param o { deployment, service, chain, limits?, onReview? } */`);
  js(`  constructor(o) { this.contract = new JoustContract({ ...o, description }); }`);
  js(doc(init));
  js(`  async deploy(wallet, args = {}${init.payable ? ', pay = {}' : ''}) {`);
  js(`    const r = await this.contract.deploy(wallet, args${init.payable ? ', pay' : ''});`);
  js(`    return { ...r, instance: this.at(r.instance) };`);
  js(`  }`);
  js(`  /** An instance by its id (the thread token's name, hex). */`);
  js(`  at(instanceId) { return new ${C}Instance(this.contract.at(instanceId)); }`);
  js(`}`);
  js();
  ts.push(`export declare class ${C} {`);
  ts.push(`  constructor(o: JoustOptions);`);
  ts.push(`  readonly contract: JoustContract;`);
  ts.push(`  deploy(wallet: Cip30Api, args: ${argsType(init)}${payParam(init)}): Promise<CallResult & { instance: ${C}Instance }>;`);
  ts.push(`  at(instanceId: Hex): ${C}Instance;`);
  ts.push(`}`);

  // ---- an instance
  js(`export class ${C}Instance {`);
  js(`  constructor(i) { this.i = i; this.id = i.id; }`);
  js(`  /** The state from the chain: { ref, state, lovelace }, or null once destroyed. */`);
  js(`  read() { return this.i.read(); }`);
  js(`  state() { return this.i.state(); }`);
  ts.push(`export declare class ${C}Instance {`);
  ts.push(`  readonly id: Hex;`);
  ts.push(`  read(): Promise<{ ref: string; state: ${stateT}; lovelace: bigint } | null>;`);
  ts.push(`  state(): Promise<${stateT} | null>;`);
  for (const a of x.actions.filter((a) => (a.kind === 'action' || a.kind === 'destroy') && usable(a))) {
    js(doc(a));
    if (a.policies?.batched) {
      // @Batched: the call is an intent, executed later by a batch (ADR-0004).
      js(`  ${id(a.name)}(wallet, args = {}${a.payable ? ', pay = {}' : ''}) { return this.i.intent(wallet, ${JSON.stringify(a.name)}, args${a.payable ? ', pay' : ''}); }`);
      ts.push(`  /** Submits an intent for this batched call. */`);
      ts.push(`  ${id(a.name)}(wallet: Cip30Api, args${a.args.length || a.payable ? '' : '?'}: ${argsType(a)}${payParam(a)}): Promise<CallResult>;`);
    } else if (a.policies?.quorum || a.policies?.authorizedBy?.length) {
      // @Quorum: the other council members' wallets co-sign (the caller counts); @AuthorizedBy: the key's wallet.
      js(`  ${id(a.name)}(wallet, args = {}${a.payable ? ', pay = {}' : ''}, opts = {}) { return this.i.call(wallet, ${JSON.stringify(a.name)}, args, ${a.payable ? 'pay' : '{}'}, opts); }`);
      ts.push(`  ${id(a.name)}(wallet: Cip30Api, args: ${argsType(a)}${payParam(a)}, opts?: { cosigners?: Cip30Api[]; governor?: { governor: { script: string; hash: string }; signers?: Cip30Api[] } }): Promise<CallResult>;`);
    } else {
      js(`  ${id(a.name)}(wallet, args = {}${a.payable ? ', pay = {}' : ''}) { return this.i.call(wallet, ${JSON.stringify(a.name)}, args${a.payable ? ', pay' : ''}); }`);
      ts.push(`  ${id(a.name)}(wallet: Cip30Api, args${a.args.length || a.payable ? '' : '?'}: ${argsType(a)}${payParam(a)}): Promise<CallResult>;`);
    }
  }
  for (const o of x.owned) {
    const O = `${C}${id(o.simple)}Object`;
    for (const cr of x.creations.filter((c) => c.kind === 'ownedInit' && c.owned === o.type && usable(c))) {
      js(doc(cr));
      js(`  async ${id(cr.name)}(wallet, args = {}${cr.payable ? ', pay = {}' : ''}) {`);
      js(`    const r = await this.i.create(wallet, ${JSON.stringify(cr.name)}, args${cr.payable ? ', pay' : ''});`);
      js(`    return { ...r, object: new ${O}(this.i.object(r.object)) };`);
      js(`  }`);
      ts.push(`  ${id(cr.name)}(wallet: Cip30Api, args${cr.args.length || cr.payable ? '' : '?'}: ${argsType(cr)}${payParam(cr)}): Promise<CallResult & { object: ${O} }>;`);
    }
    js(`  /** One ${o.simple} of this instance, by its id. */`);
    js(`  ${id(o.lookup)}(objectId) { return new ${O}(this.i.object(objectId)); }`);
    ts.push(`  ${id(o.lookup)}(objectId: Hex): ${O};`);
  }
  // Keyed types (ADR-0016 D11): inserts, lookup by key, the list's keys.
  const keyedTypes = (x.keyed ?? []).filter((k) => typeof k === 'object');
  // A generated member never hides another (F83): the keyed wrappers' own members are reserved.
  const KEYED_OBJECT_MEMBERS = new Set(['constructor', 'o', 'key', 'read']);
  const instanceMembers = new Set(['constructor', 'i', 'id', 'read', 'state', 'objects',
    ...x.actions.filter((a) => a.kind === 'action' || a.kind === 'destroy').map((a) => id(a.name))]);
  for (const k of keyedTypes) {
    for (const m of [id(k.lookup), id(k.lookup) + 'Exists', id(k.lookup) + 'Keys']) {
      if (instanceMembers.has(m)) throw new Error(`${x.contract}: the generated member ${m} of keyed type ${k.simple} clashes with another member`);
      instanceMembers.add(m);
    }
  }
  for (const cr of x.creations.filter((c) => c.kind === 'keyedInit')) {
    if (instanceMembers.has(id(cr.name))) throw new Error(`${x.contract}: keyed insert ${cr.name} clashes with a generated member of the instance`);
    instanceMembers.add(id(cr.name));
  }
  for (const a of x.actions.filter((a) => ['keyedAction', 'keyedRemove', 'keyedRetire'].includes(a.kind))) {
    if (KEYED_OBJECT_MEMBERS.has(id(a.name))) throw new Error(`${x.contract}: keyed call ${a.name} clashes with the generated object's ${id(a.name)}`);
  }
  for (const k of keyedTypes) {
    const K = `${C}${id(k.simple)}Object`;
    for (const cr of x.creations.filter((c) => c.kind === 'keyedInit' && c.keyed === k.simple)) {
      js(doc(cr));
      js(`  async ${id(cr.name)}(wallet, args = {}${cr.payable ? ', pay = {}' : ''}, opts = {}) {`);
      js(`    const r = await this.i.keyed(${JSON.stringify(k.simple)}).insert(wallet, ${JSON.stringify(cr.name)}, args, ${cr.payable ? 'pay' : '{}'}, opts);`);
      js(`    return { ...r, object: new ${K}(this.i.keyed(${JSON.stringify(k.simple)}).object(r.key)) };`);
      js(`  }`);
      ts.push(`  ${id(cr.name)}(wallet: Cip30Api, args${cr.args.length || cr.payable ? '' : '?'}: ${argsType(cr)}${payParam(cr)}, opts?: { abandon?: boolean }): Promise<CallResult & { key: Hex; object: ${K} }>;`);
    }
    js(`  /** The ${k.simple} of a key (hex), live or retired (ADR-0016). */`);
    js(`  ${id(k.lookup)}(key) { return new ${K}(this.i.keyed(${JSON.stringify(k.simple)}).object(key)); }`);
    js(`  /** Whether a ${k.simple} key is taken (live or retired); "not found" is what the chain API returned. */`);
    js(`  ${id(k.lookup)}Exists(key) { return this.i.keyed(${JSON.stringify(k.simple)}).exists(key); }`);
    js(`  /** Every ${k.simple} key, in list order (walked from the head). */`);
    js(`  ${id(k.lookup)}Keys() { return this.i.keyed(${JSON.stringify(k.simple)}).keys(); }`);
    ts.push(`  ${id(k.lookup)}(key: Hex): ${K};`);
    ts.push(`  ${id(k.lookup)}Exists(key: Hex): Promise<boolean>;`);
    ts.push(`  ${id(k.lookup)}Keys(): Promise<Array<{ key: Hex; retired: boolean; value: unknown }>>;`);
  }
  if (x.owned.length) {
    js(`  /** Every owned object of this instance on chain. */`);
    js(`  objects() { return this.i.objects(); }`);
    ts.push(`  objects(): Promise<Array<{ id: Hex; type: string; value: unknown; lovelace: bigint }>>;`);
  }
  js(`}`);
  js();
  ts.push(`}`);

  // ---- owned objects
  for (const o of x.owned) {
    const O = `${C}${id(o.simple)}Object`;
    const valueT = tsType({ $ref: '#/definitions/' + o.type.replace(/~/g, '~0').replace(/\//g, '~1') }, defs, names, false);
    js(`export class ${O} {`);
    js(`  constructor(o) { this.o = o; this.id = o.id; }`);
    js(`  /** The object from the chain: { ref, type, value, lovelace }, or null once closed. */`);
    js(`  read() { return this.o.read(); }`);
    ts.push(`export declare class ${O} {`);
    ts.push(`  readonly id: Hex;`);
    ts.push(`  read(): Promise<{ ref: string; type: string; value: ${valueT}; lovelace: bigint } | null>;`);
    for (const a of x.actions.filter((a) => (a.kind === 'ownedAction' || a.kind === 'ownedDestroy') && a.owned === o.type && usable(a))) {
      js(doc(a));
      js(`  ${id(a.name)}(wallet, args = {}${a.payable ? ', pay = {}' : ''}) { return this.o.call(wallet, ${JSON.stringify(a.name)}, args${a.payable ? ', pay' : ''}); }`);
      ts.push(`  ${id(a.name)}(wallet: Cip30Api, args${a.args.length || a.payable ? '' : '?'}: ${argsType(a)}${payParam(a)}): Promise<CallResult>;`);
    }
    js(`}`);
    js();
    ts.push(`}`);
  }
  // ---- keyed objects (ADR-0016)
  for (const k of keyedTypes) {
    const K = `${C}${id(k.simple)}Object`;
    const valueT = tsType({ $ref: '#/definitions/' + k.type.replace(/~/g, '~0').replace(/\//g, '~1') }, defs, names, false);
    js(`export class ${K} {`);
    js(`  constructor(o) { this.o = o; this.key = o.key; }`);
    js(`  /** The object from the chain: { ref, key, retired, value, lovelace }, or null. */`);
    js(`  read() { return this.o.read(); }`);
    ts.push(`export declare class ${K} {`);
    ts.push(`  readonly key: Hex;`);
    ts.push(`  read(): Promise<{ ref: string; key: Hex; retired: boolean; value: ${valueT} | null; lovelace: bigint } | null>;`);
    for (const a of x.actions.filter((a) => ['keyedAction', 'keyedRemove', 'keyedRetire'].includes(a.kind) && a.keyed === k.simple)) {
      js(doc(a));
      js(`  ${id(a.name)}(wallet, args = {}${a.payable ? ', pay = {}' : ''}, opts = {}) { return this.o.call(wallet, ${JSON.stringify(a.name)}, args, ${a.payable ? 'pay' : '{}'}, opts); }`);
      ts.push(`  ${id(a.name)}(wallet: Cip30Api, args${a.args.length || a.payable ? '' : '?'}: ${argsType(a)}${payParam(a)}, opts?: { cosigners?: Cip30Api[]; abandon?: boolean }): Promise<CallResult>;`);
    }
    js(`}`);
    js();
    ts.push(`}`);
  }
  return { js: jsLines.join('\n') + '\n', dts: ts.join('\n') + '\n' };
}
