package org.julclang.state.processor.gen;

import org.julclang.state.processor.ir.ContractIR;

/** Generates {@code <Name>Client}, the typed off-chain client (ADR-0001 D13). Placeholder: being implemented. */
public final class ClientGenerator {

    private ClientGenerator() {}

    public static String generate(ContractIR c) {
        return "package " + c.packageName() + ";\n\n/** GENERATED by the JOUST processor. Client generation is in progress. */\n"
                + "public final class " + c.clientName() + " {\n    private " + c.clientName() + "() {}\n}\n";
    }
}
