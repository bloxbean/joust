package org.julclang.state.processor.gen;

import org.julclang.state.processor.ir.ContractIR;
import org.julclang.state.processor.ir.ParamIR;
import org.julclang.state.processor.ir.TransitionIR;
import org.julclang.state.processor.ir.ViewIR;

import java.util.ArrayList;
import java.util.List;
import java.util.TreeSet;

/**
 * Generates {@code <Name>Client}: a thin typed facade over {@code julc-state-runtime} (ADR-0001 D13). One static
 * {@code deploy} per {@code @Init}, one method per {@code @Action}/{@code @Destroy}/{@code @View}. Each call method
 * describes the call (policy annotations, JVM run, redeemer) and hands it to the runtime.
 */
public final class ClientGenerator {

    /** Client members and generated parameter names a contract may not reuse (checked by the reader). */
    public static final List<String> RESERVED_MEMBERS = List.of("deploy", "at", "contract", "state", "instance",
            "instanceId", "lovelace", "SPEC");
    public static final List<String> RESERVED_PARAMS = List.of("callerAccount", "payLovelace", "runtime");

    private final ContractIR c;
    private final SourceWriter w = new SourceWriter();

    private ClientGenerator(ContractIR c) {
        this.c = c;
    }

    public static String generate(ContractIR contract) {
        return new ClientGenerator(contract).render();
    }

    private String render() {
        String X = c.name();
        String S = c.stateType();
        String V = c.validatorName();
        String C = c.clientName();

        w.line("package " + c.packageName() + ";").blank();
        var imports = new TreeSet<>(List.of("java.math.BigInteger", "com.bloxbean.cardano.client.account.Account",
                "org.julclang.state.runtime.Call", "org.julclang.state.runtime.CallResult",
                "org.julclang.state.runtime.ContractSpec", "org.julclang.state.runtime.Deploy",
                "org.julclang.state.runtime.StateContractHandle", "org.julclang.state.runtime.StateInstance",
                "org.julclang.state.runtime.StateRuntime", "org.julclang.state.runtime.Transition"));
        if (c.hasOwned()) imports.add("org.julclang.state.runtime.OwnedObject");
        imports.addAll(c.imports());
        for (String i : imports) w.line("import " + i + ";");
        w.blank();

        w.line("/**");
        w.line(" * GENERATED by the JOUST processor from {@link " + X + "}. Do not edit.");
        w.line(" * <p>");
        w.line(" * Typed client for one " + X + " instance. Each call runs the contract's own method on the JVM first (a");
        w.line(" * failing {@code Require} throws before anything is submitted), then builds, submits and confirms the");
        w.line(" * transaction through {@link StateRuntime}.");
        w.line(" */");
        w.open("public final class " + C + " {").blank();
        w.line("public static final ContractSpec<" + S + "> SPEC = new ContractSpec<>(\"" + X + "\", " + V + ".class, "
                + S + ".class, " + c.minAda() + "L, " + c.maxDatumBytes() + ", " + c.maxValidityMs() + "L);").blank();
        w.line("private final StateInstance<" + S + "> instance;").blank();
        w.open("private " + C + "(StateInstance<" + S + "> instance) {");
        w.line("this.instance = instance;");
        w.close("}").blank();

        w.line("/** The contract on a network: script, policy id, address. */");
        w.open("public static StateContractHandle<" + S + "> contract(StateRuntime runtime) {");
        w.line("return new StateContractHandle<>(runtime, SPEC);");
        w.close("}").blank();

        // ---- deploy
        TransitionIR init = c.init();
        var deployParams = new ArrayList<String>(List.of("StateRuntime runtime", "Account callerAccount"));
        deployParams.addAll(decls(init.params()));
        if (init.payable()) deployParams.add("BigInteger payLovelace");
        w.line("/** Creates a new instance by running {@link " + X + "#" + init.method() + "}. */");
        w.open("public static " + C + " deploy(" + String.join(", ", deployParams) + ") {");
        w.line("var result = contract(runtime).deploy(new Deploy<" + S + ">(callerAccount, "
                + (init.payable() ? "payLovelace" : "BigInteger.ZERO") + ", " + init.hasCtx() + ",");
        w.line("        ctx -> " + X + "." + init.method() + "(" + callArgs(init, List.of()) + "),");
        w.line("        (seed, ctx) -> new " + V + ".CreateInstance(" + redeemerArgs(init, "seed") + ")));");
        w.line("return new " + C + "(result.instance());");
        w.close("}").blank();

        w.line("/** Reconnects to an existing instance. */");
        w.open("public static " + C + " at(StateRuntime runtime, String instanceId) {");
        w.line("return new " + C + "(contract(runtime).at(instanceId));");
        w.close("}").blank();

        // ---- actions and destroys
        for (TransitionIR t : c.spendTransitions()) call(t);

        // ---- views
        for (ViewIR v : c.views()) {
            var args = new ArrayList<String>(List.of("s"));
            for (ParamIR p : v.params()) args.add(p.name());
            w.line("/** {@link " + X + "#" + v.method() + "} on the current state (off-chain, no transaction). */");
            w.open("public " + v.returnType() + " " + v.method() + "(" + String.join(", ", decls(v.params())) + ") {");
            w.line("return instance.view(s -> " + X + "." + v.method() + "(" + String.join(", ", args) + "));");
            w.close("}").blank();
        }

        if (c.hasOwned()) owned();

        w.line("/** The current state. */");
        w.open("public " + S + " state() {");
        w.line("return instance.state();");
        w.close("}").blank();
        w.line("/** Lovelace the instance holds, deposit included. */");
        w.open("public BigInteger lovelace() {");
        w.line("return instance.lovelace();");
        w.close("}").blank();
        w.open("public String instanceId() {");
        w.line("return instance.instanceId();");
        w.close("}").blank();
        w.open("public StateInstance<" + S + "> instance() {");
        w.line("return instance;");
        w.close("}");
        w.close("}");
        return w.toString();
    }

    private void call(TransitionIR t) {
        String X = c.name();
        String S = c.stateType();
        String V = c.validatorName();
        boolean destroy = t.kind() == TransitionIR.Kind.DESTROY;
        var params = new ArrayList<String>(List.of("Account callerAccount"));
        params.addAll(decls(t.params()));
        if (t.payable()) params.add("BigInteger payLovelace");

        w.line("/** Calls {@link " + X + "#" + t.method() + "}" + (destroy ? "; ends the instance." : ".") + " */");
        w.open("public CallResult<" + S + "> " + t.method() + "(" + String.join(", ", params) + ") {");
        String start = destroy
                ? "Call.<" + S + ">destroy(\"" + t.method() + "\", callerAccount, new " + V + ".BurnInstance())"
                : "Call.<" + S + ">action(\"" + t.method() + "\", callerAccount)";
        w.line("return instance.call(" + start);
        w.indent();
        w.indent();
        w.line(".usesCtx(" + t.hasCtx() + ")");
        if (t.payable()) w.line(".received(payLovelace)");
        for (String f : t.signedBy()) w.line(".signedBy(\"" + f + "\", s -> s." + f + "())");
        for (String f : t.validAfter()) w.line(".validAfter(\"" + f + "\", s -> s." + f + "())");
        for (String f : t.validBefore()) w.line(".validBefore(\"" + f + "\", s -> s." + f + "())");
        String invoke = X + "." + t.method() + "(" + callArgs(t, List.of("s")) + ")";
        switch (t.returns()) {
            case STATE -> w.line(".run((s, ctx) -> Transition.of(" + invoke + "))");
            case RESULT -> w.line(".run((s, ctx) -> { var r = " + invoke + "; return Transition.of(r.state(), r.payouts()); })");
            case PAYOUTS -> w.line(".run((s, ctx) -> Transition.end(" + invoke + "))");
        }
        w.line(".redeemer(ctx -> new " + V + "." + t.variant() + "(" + redeemerArgs(t, null) + "))");
        w.line(".build());");
        w.close("");
        w.close("}").blank();
    }

    /** Owned objects (ADR-0003): a codec, creation methods, a lookup, and a typed handle per object. */
    private void owned() {
        String X = c.name();
        String S = c.stateType();
        String R = c.ownedType();
        String V = c.validatorName();
        String simple = R.substring(R.lastIndexOf('.') + 1);
        String handle = simple + "Object";
        String codec = simple.replaceAll("([a-z])([A-Z])", "$1_$2").toUpperCase() + "_CODEC";
        String lookup = Character.toLowerCase(simple.charAt(0)) + simple.substring(1);

        w.line("/** How " + V + ".Holding wraps a " + simple + " (ADR-0003 D2). */");
        w.line("public static final OwnedObject.Codec<" + R + "> " + codec + " = new OwnedObject.Codec<>(" + V
                + ".Holding.class,");
        w.line("        h -> ((" + V + ".Holding) h).value(), (inst, v) -> new " + V + ".Holding(inst, v));").blank();

        for (TransitionIR t : c.ownedInits()) {
            var params = new ArrayList<String>(List.of("Account callerAccount"));
            params.addAll(decls(t.params()));
            if (t.payable()) params.add("BigInteger payLovelace");
            var runArgs = new ArrayList<String>();
            if (t.shared()) runArgs.add("(" + S + ") sh");
            t.params().forEach(p -> runArgs.add(p.name()));
            if (t.hasCtx()) runArgs.add("ctx");
            var redArgs = new ArrayList<String>(List.of("seed", "inst"));
            t.params().forEach(p -> redArgs.add(p.name()));
            if (t.hasCtx()) redArgs.add("ctx");
            w.line("/** Creates a " + simple + " under this instance with {@link " + X + "#" + t.method() + "}. */");
            w.open("public " + handle + " " + t.method() + "(" + String.join(", ", params) + ") {");
            w.line("return new " + handle + "(OwnedObject.create(instance, new OwnedObject.Create<" + R + ">(\"" + t.method()
                    + "\", callerAccount, " + (t.payable() ? "payLovelace" : "BigInteger.ZERO") + ", " + t.hasCtx() + ", "
                    + t.shared() + ",");
            w.line("        (sh, ctx) -> " + X + "." + t.method() + "(" + String.join(", ", runArgs) + "),");
            w.line("        (seed, inst, ctx) -> new " + V + "." + t.variant() + "(" + String.join(", ", redArgs) + ")), "
                    + codec + "));");
            w.close("}").blank();
        }
        w.line("/** An existing " + simple + " of this instance. */");
        w.open("public " + handle + " " + lookup + "(String objectId) {");
        w.line("return new " + handle + "(OwnedObject.at(instance, objectId, " + codec + "));");
        w.close("}").blank();

        w.line("/** One " + simple + ": its own UTxO; calls on it never contend with other objects. */");
        w.open("public final class " + handle + " {");
        w.line("private final OwnedObject<" + S + ", " + R + "> object;").blank();
        w.open(handle + "(OwnedObject<" + S + ", " + R + "> object) {");
        w.line("this.object = object;");
        w.close("}").blank();
        w.line("public String objectId() { return object.objectId(); }");
        w.line("public " + R + " value() { return object.value(); }");
        w.line("public BigInteger lovelace() { return object.lovelace(); }").blank();
        for (TransitionIR t : c.ownedSpendTransitions()) {
            boolean destroy = t.destroys();
            var params = new ArrayList<String>(List.of("Account callerAccount"));
            params.addAll(decls(t.params()));
            if (t.payable()) params.add("BigInteger payLovelace");
            w.open("public CallResult<" + R + "> " + t.method() + "(" + String.join(", ", params) + ") {");
            String start = destroy
                    ? "Call.<" + R + ">destroy(\"" + t.method() + "\", callerAccount, new " + V + ".BurnInstance())"
                    : "Call.<" + R + ">action(\"" + t.method() + "\", callerAccount)";
            w.line("return object.call(" + start);
            w.indent();
            w.indent();
            w.line(".usesCtx(" + t.hasCtx() + ")");
            if (t.payable()) w.line(".received(payLovelace)");
            for (String f : t.signedBy()) w.line(".signedBy(\"" + f + "\", o -> o." + f + "())");
            for (String f : t.validAfter()) w.line(".validAfter(\"" + f + "\", o -> o." + f + "())");
            for (String f : t.validBefore()) w.line(".validBefore(\"" + f + "\", o -> o." + f + "())");
            var callArgs = new ArrayList<String>(List.of("o"));
            if (t.shared()) callArgs.add("(" + S + ") sh");
            t.params().forEach(p -> callArgs.add(p.name()));
            if (t.hasCtx()) callArgs.add("ctx");
            String invoke = X + "." + t.method() + "(" + String.join(", ", callArgs) + ")";
            String body = switch (t.returns()) {
                case STATE -> "Transition.of(" + invoke + ")";
                case RESULT -> "Transition.of(" + invoke + ".state(), " + invoke + ".payouts())";
                case PAYOUTS -> "Transition.end(" + invoke + ")";
            };
            if (t.returns() == TransitionIR.Returns.RESULT) {
                body = null;
                w.line(t.shared() ? ".runShared((o, sh, ctx) -> { var r = " + invoke + "; return Transition.of(r.state(), r.payouts()); })"
                        : ".run((o, ctx) -> { var r = " + invoke + "; return Transition.of(r.state(), r.payouts()); })");
            } else {
                w.line(t.shared() ? ".runShared((o, sh, ctx) -> " + body + ")" : ".run((o, ctx) -> " + body + ")");
            }
            w.line(".redeemer(ctx -> new " + V + "." + t.variant() + "(" + redeemerArgs(t, null) + "))");
            w.line(".build());");
            w.close("");
            w.close("}").blank();
        }
        w.close("}").blank();
    }

    private static List<String> decls(List<ParamIR> ps) {
        var out = new ArrayList<String>();
        for (ParamIR p : ps) out.add(p.type() + " " + p.name());
        return out;
    }

    /** Arguments of the contract method: leading (state), parameters, then ctx if declared. */
    private static String callArgs(TransitionIR t, List<String> leading) {
        var out = new ArrayList<>(leading);
        for (ParamIR p : t.params()) out.add(p.name());
        if (t.hasCtx()) out.add("ctx");
        return String.join(", ", out);
    }

    /** Components of the redeemer record: [seed], parameters, ctx if declared, map witnesses if any. */
    private String redeemerArgs(TransitionIR t, String seed) {
        var out = new ArrayList<String>();
        if (seed != null) out.add(seed);
        for (ParamIR p : t.params()) out.add(p.name());
        if (t.hasCtx()) out.add("ctx");
        return String.join(", ", out);
    }
}
