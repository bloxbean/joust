    /** The state expression, checked against the invariants on the JVM if there are any for this subject. */
    /** {@code expr} checked against the invariants of its subject: an owned record's type, or null for the state. */
    private String st(String expr, String ownedType) {
        boolean any = c.invariants().stream().anyMatch(i -> java.util.Objects.equals(i.ownedType(), ownedType));
        if (!any) return expr;
        return checkedName(ownedType) + "(" + expr + (c.hasParams() ? ", params" : "") + ")";
    }

    private String checkedName(String ownedType) {
        return ownedType == null ? "checkedState" : "checked" + c.ownedOf(ownedType).simple();
    }

    private static String events(TransitionIR t) {
        return t.resultEvents() ? ".withEvents(r.events())" : "";
    }

    private void invariantHelpers() {
        var subjects = new ArrayList<String>();
        subjects.add(null);
        c.owned().forEach(o -> subjects.add(o.type()));
        for (String subject : subjects) {
            var invs = c.invariants().stream().filter(i -> java.util.Objects.equals(i.ownedType(), subject)).toList();
            if (invs.isEmpty()) continue;
            String T = subject != null ? subject : c.stateType();
            String name = checkedName(subject);
            w.line("/** {@code s}, after checking every @Invariant on the JVM (the validator checks them again; ADR-0009 D4). */");
            w.open("static " + T + " " + name + "(" + T + " s" + (c.hasParams() ? ", " + c.paramsType() + " params" : "") + ") {");
            for (var inv : invs) {
                w.line("if (!" + c.name() + "." + inv.method() + "(s" + (inv.takesParams() ? ", params" : "")
                        + ")) throw new org.julclang.state.api.RequireException(\"invariant " + inv.method() + "\");");
            }
            w.line("return s;");
            w.close("}").blank();
        }
    }

    /** Extra client parameters: the authorization and the co-signers. */
    private static void extraParams(TransitionIR t, List<String> params) {
        if (!t.authorizedBy().isEmpty()) params.add("org.julclang.state.runtime.Authorization authorization");
        if (t.quorumKeys() != null) params.add("Account... cosigners");
    }

    private static void extraCalls(TransitionIR t) {
    }

    /** Reads each {@code @Reads} instance before the call; its UTxO becomes a reference input (ADR-0011 D2). */
    private void fetchReads(TransitionIR t, String runtime) {
        for (var rd : t.reads()) {
            w.line("var read_" + rd.name() + " = org.julclang.state.runtime.ForeignReads.read(" + runtime + ", params."
                    + rd.path().substring(7) + "(), " + rd.type() + ".class);");
        }
    }

    private void redeemerLine(TransitionIR t) {
        redeemerLine(t, true);
    }

    /** {@code readsAsInputs}: the reads' UTxOs as fixed reference inputs (a keyed call passes them as reads instead). */
    private void redeemerLine(TransitionIR t, boolean readsAsInputs) {
        String V = c.validatorName();
        if (readsAsInputs && !t.reads().isEmpty()) {
            var refs = new ArrayList<String>();
            for (var rd : t.reads()) refs.add("read_" + rd.name() + ".utxo()");
            w.line(".referenceInputs(" + String.join(", ", refs) + ")");
        }
        if (!t.authorizedBy().isEmpty()) w.line(".authorization(authorization)");
        if (t.quorumKeys() != null) w.line(".cosigners(cosigners)");
        if (t.resultEvents()) {
            String args = redeemerArgs(t, null);
            args = args.isEmpty() ? "" : args + ", ";
            w.line(".redeemerWith((ctx, tr) -> new " + V + "." + t.variant() + "(" + args + "(" + t.eventsType() + ") tr.events()))");
        } else {
            w.line(".redeemer(ctx -> new " + V + "." + t.variant() + "(" + redeemerArgs(t, null) + "))");
        }
    }

    /** {@code Transition.full(...)} from a method's result {@code r}. */
    private String transitionExpr(TransitionIR t, String r) {
        return switch (t.returns()) {
            case STATE -> "Transition.full(" + st(r, t.ownedType()) + ", null, null, null, null)";
            case PAYOUTS -> "Transition.full(null, " + r + ", null, null, null)";
            case RESULT, SETTLE -> "Transition.full(" + (t.returns() == TransitionIR.Returns.RESULT ? st(r + ".state()", t.ownedType()) : "null")
                    + ", " + (t.resultPayouts() ? r + ".payouts()" : "null")
                    + ", " + (t.resultSends() ? r + ".sends()" : "null")
                    + ", " + (t.resultMint() ? r + ".mint()" : "null")
                    + ", " + (t.resultAccepted() ? r + ".accepted()" : "null") + ")"
                    + (t.resultEvents() ? ".withEvents(" + r + ".events())" : "")
                    + (t.resultDeposits() ? ".withDeposits(" + r + ".deposits())" : "");
        };
    }

    private static String assetsArg(TransitionIR t) {
        return ValidatorGenerator.takesAssets(t) ? "payAssets" : "org.julclang.state.api.Assets.none()";
    }

    private static List<String> decls(List<ParamIR> ps) {
        var out = new ArrayList<String>();
        for (ParamIR p : ps) out.add(p.type() + " " + p.name());
        return out;
    }

    /** Arguments of the contract method: leading (state), parameters, then ctx if declared. */
    private static String callArgs(TransitionIR t, List<String> leading) {
        var out = new ArrayList<>(leading);
        if (t.takesParams()) out.add("params");
        for (var rd : t.reads()) out.add("read_" + rd.name() + ".state()");
        for (int i = 0; i < t.params().size(); i++) {
            out.add(t.params().get(i).name());
            if (i == 0 && t.arriving() != null) out.add(t.arriving());
        }
        if (t.hasCtx()) out.add("ctx");
        if (t.hasFunds()) out.add("funds");
        return String.join(", ", out);
    }

    /** Components of the redeemer record: [seed], parameters, ctx if declared, map witnesses if any. */
    private String redeemerArgs(TransitionIR t, String seed) {
        var out = new ArrayList<String>();
        if (seed != null) out.add(seed);
        if (t.moves()) out.add("com.bloxbean.cardano.client.util.HexUtil.decodeHexString(destination.instanceId())");
        for (ParamIR p : t.params()) out.add(p.name());
        if (t.hasCtx()) out.add("ctx");
        if (ValidatorGenerator.takesAssets(t)) out.add("payAssets.toPlutusData()");
        return String.join(", ", out);
    }
