package org.julclang.state.processor.gen;

import org.julclang.state.processor.Records;
import org.julclang.state.processor.ir.ContractIR;
import org.julclang.state.processor.ir.TransitionIR;

import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.RecordComponentElement;
import javax.lang.model.element.TypeElement;
import javax.lang.model.element.VariableElement;
import javax.lang.model.type.ArrayType;
import javax.lang.model.type.DeclaredType;
import javax.lang.model.type.TypeKind;
import javax.lang.model.type.TypeMirror;
import javax.lang.model.util.ElementFilter;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

/**
 * {@code <Name>Portable} (ADR-0013 D4, experimental; option {@code -Ajoust.portable=true}): the contract's pure
 * transitions with generated, non-reflective Plutus data codecs, for builds that cannot use reflection or
 * cardano-client-lib, such as a GraalVM Web Image (Wasm) build for the browser.
 * <p>
 * {@code step(method, target, shared, args, ctx)} takes CBOR (the current datum value, the instance state for
 * {@code @Shared} reads, the method's arguments as a list, the Ctx) and returns CBOR of
 * {@code Constr 0 [next, payouts]}, where {@code next} is {@code Constr 0 [value]} or {@code Constr 1 []} when the
 * instance or object ends. A failing {@code Require} throws, as on the JVM.
 * <p>
 * Only transitions whose inputs and result are plain data are portable: no MerkleMaps, foreign reads, params,
 * native assets, batches, moves, deposits, sends, mints or events.
 */
public final class PortableGenerator {

    private static final String API = "org.julclang.state.api.";
    private static final String LEDGER = "org.julclang.ledger.";

    private final ContractIR c;
    private final TypeElement contract;
    private final ProcessingEnvironment env;
    private final SourceWriter w = new SourceWriter();
    /** Codec name -> the type it encodes; generated after the steps. */
    private final Map<String, TypeMirror> codecs = new LinkedHashMap<>();
    private final Map<String, String> names = new LinkedHashMap<>();
    private final List<String> skipped = new ArrayList<>();

    private PortableGenerator(ContractIR c, TypeElement contract, ProcessingEnvironment env) {
        this.c = c;
        this.contract = contract;
        this.env = env;
    }

    public static String generate(ContractIR c, TypeElement contract, ProcessingEnvironment env) {
        return new PortableGenerator(c, contract, env).source();
    }

    private String source() {
        String X = c.name();
        // Steps first: they register the codecs they need.
        var body = new SourceWriter();
        var all = new ArrayList<TransitionIR>(c.spendTransitions());
        all.addAll(c.ownedSpendTransitions());
        var cases = new ArrayList<String[]>();
        for (TransitionIR t : all) {
            String reason = unsupported(t);
            if (reason != null) {
                skipped.add(t.method() + " (" + reason + ")");
                continue;
            }
            String[] k = stepCase(t);
            if (k == null) skipped.add(t.method() + " (its parameters or result are not plain data)");
            else cases.add(k);
        }

        w.line("package " + c.packageName() + ";").blank();
        w.line("import org.julclang.core.PlutusData;");
        w.line("import org.julclang.core.cbor.PlutusDataCborDecoder;");
        w.line("import org.julclang.core.cbor.PlutusDataCborEncoder;");
        w.line("import java.math.BigInteger;");
        w.line("import java.util.ArrayList;");
        w.line("import java.util.List;").blank();
        w.line("/**");
        w.line(" * GENERATED by the JOUST processor from {@link " + X + "} (-Ajoust.portable=true). Do not edit.");
        w.line(" * <p>");
        w.line(" * The contract's pure transitions with non-reflective Plutus data codecs (ADR-0013 D4, experimental): for");
        w.line(" * reflection-free builds such as GraalVM Web Image (Wasm). See {@code step}.");
        if (!skipped.isEmpty()) w.line(" * Not portable: " + String.join(", ", skipped) + ".");
        w.line(" */");
        w.line("@SuppressWarnings({\"unchecked\", \"rawtypes\"})");
        w.open("public final class " + X + "Portable {").blank();
        w.line("private " + X + "Portable() {").line("}").blank();
        w.line("/** The portable methods. */");
        w.line("public static final String[] METHODS = {" + String.join(", ", cases.stream().map(k -> "\"" + k[0] + "\"").toList()) + "};").blank();
        w.line("/**");
        w.line(" * Runs {@code method}: CBOR in (the target's value, the instance state for @Shared reads or empty, the arguments");
        w.line(" * as a list, the Ctx or empty), CBOR out: Constr 0 [Constr 0 [next] | Constr 1 [], payouts].");
        w.line(" */");
        w.open("public static byte[] step(String method, byte[] target, byte[] shared, byte[] args, byte[] ctx) {");
        if (cases.isEmpty()) {
            w.line("throw new IllegalArgumentException(\"no portable method \" + method);");
            w.close("}").blank();
        } else {
        w.line("PlutusData t = PlutusDataCborDecoder.decode(target);");
        w.line("PlutusData sh = shared == null || shared.length == 0 ? null : PlutusDataCborDecoder.decode(shared);");
        w.line("List<PlutusData> a = ((PlutusData.ListData) PlutusDataCborDecoder.decode(args)).items();");
        w.line("PlutusData cx = ctx == null || ctx.length == 0 ? null : PlutusDataCborDecoder.decode(ctx);");
        w.open("PlutusData out = switch (method) {");
        for (String[] k : cases) w.line("case \"" + k[0] + "\" -> " + k[1] + (k[1].startsWith("{") ? "" : ";"));
        w.line("default -> throw new IllegalArgumentException(\"no portable method \" + method);");
        w.close("};");
        w.line("return PlutusDataCborEncoder.encode(out);");
        w.close("}").blank();
        }
        w.open("private static PlutusData result(PlutusData next, PlutusData payouts) {");
        w.line("return new PlutusData.ConstrData(0, List.of(next == null ? new PlutusData.ConstrData(1, List.of())"
                + " : new PlutusData.ConstrData(0, List.of(next)), payouts));");
        w.close("}").blank();
        w.open("private static List<PlutusData> fields(PlutusData d, int tag, int n) {");
        w.line("if (!(d instanceof PlutusData.ConstrData c) || c.tag() != tag || c.fields().size() != n) {");
        w.line("    throw new IllegalArgumentException(\"expected constructor \" + tag + \" with \" + n + \" fields\");");
        w.line("}");
        w.line("return c.fields();");
        w.close("}").blank();
        w.open("private static int tag(PlutusData d) {");
        w.line("if (!(d instanceof PlutusData.ConstrData c)) throw new IllegalArgumentException(\"expected a constructor\");");
        w.line("return c.tag();");
        w.close("}").blank();
        // Codecs (generating one may register others).
        var done = new java.util.HashSet<String>();
        while (done.size() < codecs.size()) {
            for (var e : new ArrayList<>(codecs.entrySet())) {
                if (done.add(e.getKey())) codec(e.getKey(), e.getValue());
            }
        }
        w.close("}");
        return w.toString();
    }

    private static String unsupported(TransitionIR t) {
        if (t.takesParams()) return "params";
        if (!t.reads().isEmpty()) return "foreign reads";
        if (t.hasFunds() || ValidatorGenerator.takesAssets(t)) return "native assets";
        if (t.batched()) return "batched";
        if (t.moves() || t.admits() || t.receives() || t.resultDeposits()) return "composition";
        if (t.resultSends() || t.resultMint() || t.resultAccepted() || t.resultEvents()) return "sends, mints or events";
        return null;
    }

    /** {@code {method, expression}} for a step, or null when a parameter or the result is not plain data. */
    private String[] stepCase(TransitionIR t) {
        ExecutableElement m = method(t.method());
        if (m == null) return null;
        var argNames = t.params().stream().map(p -> p.name()).toList();
        var call = new ArrayList<String>();
        boolean first = true;
        for (VariableElement p : m.getParameters()) {
            TypeMirror pt = p.asType();
            String name = p.getSimpleName().toString();
            Optional<String> dec;
            if (first) {
                dec = decoder(pt, "t");
                first = false;
            } else if (hasAnnotation(p, API + "Shared")) {
                dec = decoder(pt, "sh");
            } else if (isNamed(pt, API + "Ctx")) {
                dec = decoder(pt, "cx");
            } else if (argNames.contains(name)) {
                dec = decoder(pt, "a.get(" + argNames.indexOf(name) + ")");
            } else {
                return null;
            }
            if (dec.isEmpty()) return null;
            call.add(dec.get());
        }
        String invoke = c.name() + "." + t.method() + "(" + String.join(", ", call) + ")";
        TypeMirror r = m.getReturnType();
        TypeMirror target = m.getParameters().get(0).asType();
        String none = "new PlutusData.ListData(List.of())";
        if (env.getTypeUtils().isSameType(r, target)) {
            return encoder(r, invoke).map(e -> new String[]{t.method(), "result(" + e + ", " + none + ")"}).orElse(null);
        }
        if (isPayouts(r)) {
            return encoder(r, invoke).map(e -> new String[]{t.method(), "result(null, " + e + ")"}).orElse(null);
        }
        if (r instanceof DeclaredType d && ((TypeElement) d.asElement()).getKind() == ElementKind.RECORD) {
            TypeMirror state = null, payouts = null;
            for (RecordComponentElement rc : Records.components(((TypeElement) d.asElement()))) {
                switch (rc.getSimpleName().toString()) {
                    case "state" -> state = rc.asType();
                    case "payouts" -> payouts = rc.asType();
                    default -> {
                        return null;
                    }
                }
            }
            String rt = env.getTypeUtils().erasure(r).toString();
            var next = state == null ? Optional.of("null") : encoder(state, "r.state()");
            var pays = payouts == null ? Optional.of(none) : encoder(payouts, "r.payouts()");
            if (next.isEmpty() || pays.isEmpty()) return null;
            return new String[]{t.method(), "{ " + rt + " r = " + invoke + "; yield result(" + next.get() + ", " + pays.get() + "); }"};
        }
        return null;
    }

    // ------------------------------------------------------------------ codecs

    private Optional<String> encoder(TypeMirror t, String expr) {
        return codecName(t).map(n -> "enc_" + n + "(" + expr + ")");
    }

    private Optional<String> decoder(TypeMirror t, String expr) {
        return codecName(t).map(n -> "dec_" + n + "(" + expr + ")");
    }

    /** A codec for {@code t}, registered; empty when {@code t} is not plain data. */
    private Optional<String> codecName(TypeMirror t) {
        if (!supported(t, 0)) return Optional.empty();
        // One name per type (by its full rendering, generics included); unique even when sanitised renderings collide
        // (C.A_B and C.A.B).
        String key = t.toString();
        String n = names.get(key);
        if (n == null) {
            n = key.replaceAll("[^A-Za-z0-9]+", "_") + "_" + names.size();
            names.put(key, n);
            codecs.put(n, t);
        }
        return Optional.of(n);
    }

    private boolean supported(TypeMirror t, int depth) {
        if (depth > 16) return false;
        if (t.getKind() == TypeKind.BOOLEAN) return true;
        if (t.getKind() == TypeKind.ARRAY) return ((ArrayType) t).getComponentType().getKind() == TypeKind.BYTE;
        if (!(t instanceof DeclaredType d)) return false;
        TypeElement e = (TypeElement) d.asElement();
        String fq = e.getQualifiedName().toString();
        switch (fq) {
            case "java.math.BigInteger", "java.lang.Boolean", "java.lang.String", "org.julclang.core.PlutusData":
                return true;
            case "java.util.Optional", "org.julclang.core.types.JulcList", "org.julclang.core.types.JulcMap":
                return d.getTypeArguments().stream().allMatch(a -> supported(a, depth + 1));
            default:
                break;
        }
        if (fq.startsWith(LEDGER)) return hasStaticFromPlutusData(e);
        if (fq.startsWith(API + "mpf.") || fq.equals(API + "MerkleMap")) return false;
        if (e.getKind() == ElementKind.RECORD) {
            return Records.components(e).stream().allMatch(rc -> supported(rc.asType(), depth + 1));
        }
        if (e.getKind() == ElementKind.INTERFACE && e.getModifiers().contains(Modifier.SEALED)) {
            return e.getPermittedSubclasses().stream().allMatch(s -> supported(s, depth + 1));
        }
        return false;
    }

    private void codec(String n, TypeMirror t) {
        String type = typeName(t);
        w.open("static PlutusData enc_" + n + "(" + type + " v) {");
        w.line("return " + encodeExpr(t, "v") + ";");
        w.close("}").blank();
        w.open("static " + type + " dec_" + n + "(PlutusData d) {");
        decodeBody(t);
        w.close("}").blank();
    }

    private String encodeExpr(TypeMirror t, String v) {
        if (t.getKind() == TypeKind.BOOLEAN || isNamed(t, "java.lang.Boolean")) {
            return "new PlutusData.ConstrData(" + v + " ? 1 : 0, List.of())";
        }
        if (t.getKind() == TypeKind.ARRAY) return "new PlutusData.BytesData(" + v + ")";
        DeclaredType d = (DeclaredType) t;
        TypeElement e = (TypeElement) d.asElement();
        String fq = e.getQualifiedName().toString();
        var args = d.getTypeArguments();
        switch (fq) {
            case "java.math.BigInteger": return "new PlutusData.IntData(" + v + ")";
            case "java.lang.String": return "new PlutusData.BytesData(" + v + ".getBytes(java.nio.charset.StandardCharsets.UTF_8))";
            case "org.julclang.core.PlutusData": return v;
            case "java.util.Optional":
                return v + ".isPresent() ? new PlutusData.ConstrData(0, List.of(" + encoder(args.get(0), v + ".get()").orElseThrow()
                        + ")) : new PlutusData.ConstrData(1, List.of())";
            case "org.julclang.core.types.JulcList":
                return "listOf_" + codecName(t).orElseThrow() + "(" + v + ")";
            case "org.julclang.core.types.JulcMap":
                return "mapOf_" + codecName(t).orElseThrow() + "(" + v + ")";
            default: break;
        }
        if (fq.startsWith(LEDGER)) return v + ".toPlutusData()";
        if (e.getKind() == ElementKind.RECORD) {
            var comps = Records.components(e);
            if (isNewType(e) && comps.size() == 1) return encoder(comps.get(0).asType(), v + "." + comps.get(0).getSimpleName() + "()").orElseThrow();
            var fs = new ArrayList<String>();
            for (RecordComponentElement rc : comps) fs.add(encoder(rc.asType(), v + "." + rc.getSimpleName() + "()").orElseThrow());
            return "new PlutusData.ConstrData(" + tagOf(e) + ", List.of(" + String.join(", ", fs) + "))";
        }
        // A sealed interface: each permitted record encodes itself.
        var alts = new ArrayList<String>();
        for (TypeMirror sub : e.getPermittedSubclasses()) {
            String st = typeName(sub);
            alts.add(v + " instanceof " + st + " s" + alts.size() + " ? " + encoder(sub, "s" + alts.size()).orElseThrow());
        }
        return "(" + String.join(" : ", alts) + " : null)";
    }

    private void decodeBody(TypeMirror t) {
        if (t.getKind() == TypeKind.BOOLEAN || isNamed(t, "java.lang.Boolean")) {
            w.line("int tag = tag(d);");
            w.line("fields(d, tag, 0);");
            w.line("if (tag > 1) throw new IllegalArgumentException(\"not a Bool\");");
            w.line("return tag == 1;");
            return;
        }
        if (t.getKind() == TypeKind.ARRAY) {
            w.line("return ((PlutusData.BytesData) d).value();");
            return;
        }
        DeclaredType dt = (DeclaredType) t;
        TypeElement e = (TypeElement) dt.asElement();
        String fq = e.getQualifiedName().toString();
        var args = dt.getTypeArguments();
        switch (fq) {
            case "java.math.BigInteger" -> w.line("return ((PlutusData.IntData) d).value();");
            case "java.lang.String" -> w.line("return new String(((PlutusData.BytesData) d).value(), java.nio.charset.StandardCharsets.UTF_8);");
            case "org.julclang.core.PlutusData" -> w.line("return d;");
            case "java.util.Optional" -> {
                w.line("if (tag(d) == 1) { fields(d, 1, 0); return java.util.Optional.empty(); }");
                w.line("return java.util.Optional.of(" + decoder(args.get(0), "fields(d, 0, 1).get(0)").orElseThrow() + ");");
            }
            case "org.julclang.core.types.JulcList" -> {
                w.line("List<PlutusData> items = ((PlutusData.ListData) d).items();");
                w.line("Object[] out = new Object[items.size()];");
                w.line("for (int i = 0; i < out.length; i++) out[i] = " + decoder(args.get(0), "items.get(i)").orElseThrow() + ";");
                w.line("return (" + typeName(t) + ") (Object) org.julclang.core.types.JulcList.of(out);");
                w.dedent().line("}").blank();
                // Its encoder helper: a plain loop (streams would pull much of java.util.stream into a Wasm image).
                w.open("static PlutusData listOf_" + codecName(t).orElseThrow() + "(" + typeName(t) + " l) {");
                w.line("var out = new ArrayList<PlutusData>();");
                w.line("for (long i = 0; i < l.size(); i++) out.add(" + encoder(args.get(0), "l.get(i)").orElseThrow() + ");");
                w.line("return new PlutusData.ListData(out);");
            }
            case "org.julclang.core.types.JulcMap" -> {
                w.line("List<PlutusData.Pair> es = ((PlutusData.MapData) d).entries();");
                w.line("org.julclang.core.types.JulcMap m = org.julclang.core.types.JulcMap.empty();");
                w.line("// insert prepends: from the last entry, so the map keeps the datum's order.");
                w.line("for (int i = es.size() - 1; i >= 0; i--) m = m.insert(" + decoder(args.get(0), "es.get(i).key()").orElseThrow()
                        + ", " + decoder(args.get(1), "es.get(i).value()").orElseThrow() + ");");
                w.line("return (" + typeName(t) + ") m;");
                w.dedent().line("}").blank();
                // Its encoder helper (map entries in the map's own order).
                w.open("static PlutusData mapOf_" + codecName(t).orElseThrow() + "(" + typeName(t) + " m) {");
                w.line("var keys = m.keys();");
                w.line("var values = m.values();");
                w.line("var out = new ArrayList<PlutusData.Pair>();");
                w.line("for (long i = 0; i < keys.size(); i++) out.add(new PlutusData.Pair(" + encoder(args.get(0), "keys.get(i)").orElseThrow()
                        + ", " + encoder(args.get(1), "values.get(i)").orElseThrow() + "));");
                w.line("return new PlutusData.MapData(out);");
            }
            default -> {
                if (fq.startsWith(LEDGER)) {
                    w.line("return " + fq + ".fromPlutusData(d);");
                } else if (e.getKind() == ElementKind.RECORD) {
                    var comps = Records.components(e);
                    if (isNewType(e) && comps.size() == 1) {
                        w.line("return new " + typeName(t) + "(" + decoder(comps.get(0).asType(), "d").orElseThrow() + ");");
                    } else {
                        w.line("List<PlutusData> f = fields(d, " + tagOf(e) + ", " + comps.size() + ");");
                        var as = new ArrayList<String>();
                        for (int i = 0; i < comps.size(); i++) as.add(decoder(comps.get(i).asType(), "f.get(" + i + ")").orElseThrow());
                        w.line("return new " + typeName(t) + "(" + String.join(", ", as) + ");");
                    }
                } else {
                    w.open("return switch (tag(d)) {");
                    int i = 0;
                    for (TypeMirror sub : e.getPermittedSubclasses()) w.line("case " + i++ + " -> " + decoder(sub, "d").orElseThrow() + ";");
                    w.line("default -> throw new IllegalArgumentException(\"no variant \" + tag(d) + \" of " + e.getSimpleName() + "\");");
                    w.close("};");
                }
            }
        }
    }

    // ------------------------------------------------------------------ helpers

    private String typeName(TypeMirror t) {
        if (t.getKind() == TypeKind.BOOLEAN) return "boolean";
        if (t.getKind() == TypeKind.ARRAY) return "byte[]";
        // Canonical names (nested classes with dots) with their type arguments.
        DeclaredType d = (DeclaredType) t;
        String base = ((TypeElement) d.asElement()).getQualifiedName().toString();
        if (d.getTypeArguments().isEmpty()) return base;
        return base + "<" + String.join(", ", d.getTypeArguments().stream().map(a -> boxed(typeName(a))).toList()) + ">";
    }

    private static String boxed(String t) {
        return t.equals("boolean") ? "Boolean" : t;
    }

    private int tagOf(TypeElement record) {
        for (TypeMirror iface : record.getInterfaces()) {
            TypeElement p = (TypeElement) ((DeclaredType) iface).asElement();
            if (p.getKind() == ElementKind.INTERFACE && p.getModifiers().contains(Modifier.SEALED)) {
                int i = 0;
                for (TypeMirror sub : p.getPermittedSubclasses()) {
                    if (((DeclaredType) sub).asElement().equals(record)) return i;
                    i++;
                }
            }
        }
        return 0;
    }

    private static boolean isNewType(TypeElement e) {
        return e.getAnnotationMirrors().stream().anyMatch(a ->
                ((TypeElement) a.getAnnotationType().asElement()).getQualifiedName().contentEquals("org.julclang.stdlib.annotation.NewType"));
    }

    private static boolean hasStaticFromPlutusData(TypeElement e) {
        return ElementFilter.methodsIn(e.getEnclosedElements()).stream().anyMatch(m -> m.getSimpleName().contentEquals("fromPlutusData")
                && m.getModifiers().contains(Modifier.STATIC) && m.getParameters().size() == 1);
    }

    private boolean isPayouts(TypeMirror t) {
        return t instanceof DeclaredType d && isNamed(t, "org.julclang.core.types.JulcList") && d.getTypeArguments().size() == 1
                && isNamed(d.getTypeArguments().get(0), API + "Payout");
    }

    private static boolean isNamed(TypeMirror t, String fq) {
        return t instanceof DeclaredType d && ((TypeElement) d.asElement()).getQualifiedName().contentEquals(fq);
    }

    private static boolean hasAnnotation(VariableElement p, String fq) {
        return p.getAnnotationMirrors().stream().anyMatch(a -> ((TypeElement) a.getAnnotationType().asElement()).getQualifiedName().contentEquals(fq));
    }

    /** The contract's method {@code name}: the one carrying a JOUST annotation (an unannotated overload is a helper). */
    private ExecutableElement method(String name) {
        ExecutableElement any = null;
        for (ExecutableElement m : ElementFilter.methodsIn(contract.getEnclosedElements())) {
            if (!m.getSimpleName().contentEquals(name)) continue;
            boolean joust = m.getAnnotationMirrors().stream().anyMatch(a -> ((TypeElement) a.getAnnotationType().asElement())
                    .getQualifiedName().toString().startsWith("org.julclang.state.api."));
            if (joust) return m;
            if (any == null) any = m;
        }
        return any;
    }
}
