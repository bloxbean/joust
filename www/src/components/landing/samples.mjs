// The landing page's code: the template's Counter in Java and in .jsc (compiled by the toolchain: same contract), and
// the JavaScript that calls it from a page. Keep these in step with js/create-joust/template.
export const JAVA = `@StateContract(maxDatumBytes = 128)
public class Counter {

    public record State(BigInteger count, byte[] owner) {}

    @Init
    public static State init(Ctx ctx) {
        return new State(BigInteger.ZERO, ctx.caller());
    }

    @Action
    public static State increment(State s, BigInteger by) {
        Require.that(by.compareTo(BigInteger.ZERO) > 0, "increment must be positive");
        return new State(s.count().add(by), s.owner());
    }

    @Action @OnlyOwner
    public static State reset(State s) {
        return new State(BigInteger.ZERO, s.owner());
    }

    @Destroy @OnlyOwner
    public static JulcList<Payout> close(State s, Ctx ctx) {
        return Payouts.of(s.owner(), ctx.balance());
    }
}`;

export const JSC = `contract Counter(maxDatumBytes = 128) {
    state count: Int
    state owner: Key

    init() {
        owner = caller
    }

    action increment(by: Int) {
        require by > 0 "increment must be positive"
        count += by
    }

    action reset() only owner {
        count = 0
    }

    destroy close() only owner {
        pay balance to owner
    }
}`;

export const JS = `import { Counter } from '../build/joust/Counter.js';   // generated by joust build
import { blockfrostChain } from '@julclang/state-client';
import { engineWorker } from '@julclang/joust-runtime/page';
import net from 'virtual:joust/network';

// The runtime engine runs in a Web Worker: the page builds its own transactions.
const service = engineWorker(new Worker(new URL('./engine.worker.js', import.meta.url),
  { type: 'module' }), net);
const chain = blockfrostChain(new URL(net.chain, location.href).href);
const counter = new Counter({ service, chain, deployment: net.deployments['app.Counter'] });
const wallet = await window.cardano.eternl.enable();          // any CIP-30 wallet

const { instance } = await counter.deploy(wallet, {});   // the wallet signs
await instance.increment(wallet, { by: 1n });            // verified by the page first
await instance.increment(wallet, { by: 0n });            // refused: "increment must be positive"`;

